package main

import (
	"os"
	"path/filepath"
	"testing"
)

// writeLicenseDir creates a temp directory holding the given files, the
// shape of a module cache source directory.
func writeLicenseDir(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// writeModule creates a fake module with the given files, returning its
// moduleInfo.
func writeModule(t *testing.T, path string, files map[string]string) moduleInfo {
	t.Helper()
	return moduleInfo{Path: path, Version: "v1.0.0", Dir: writeLicenseDir(t, files)}
}

